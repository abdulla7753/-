def build(lang):
    out = {"@@locale": lang}
    for k, (en, ar, ph) in S.items():
        out[k] = en if lang == "en" else ar
        if lang == "en" and ph:
            out["@" + k] = {"placeholders": {p: {"type": t} for p, t in ph.items()}}
    return out
